"""Verdict axes from the dcat-ap-plus-p450 specification (section 7), plus check markers.

1. Gate letters for empty/absent answers: + witnessed absent, - not recorded,
   a both, open a name the source never uses, ? undecided.
2. Ground verdicts from a provenance chain:
   CHAIN = wasGeneratedBy / (used / wasGeneratedBy)*;  g = generation recorded,
   c = a contact activity (a measurement of the object) reachable, d = a derivation
   reachable.  000 symbol, 100 collapsed, 110 index, 101 icon, 111 composite.
3. Stage digests: a derived value is valid only for the content and conventions it
   was computed on (R5); `is_current` recomputes and compares.
4. Ladder floor: `judge_ladder` returns SUBFLOOR with the named shortfall when the
   composite power 1 - prod(1 - p_i) is below its declared target.
5. Check markers (from the empty-dictionary paper): a check whose control also
   passes is reported as non-discriminating rather than as a pass.
"""
from __future__ import annotations

import hashlib
import json
from collections import Counter
from pathlib import Path

from .core import Label, Verdict, answered

# ------------------------------------------------------------------ gate letters

# blocker text (or its start) -> gate letter; anything unmatched is undecided
GATE_RULES = [
    ("no TECRDB measurement of this reaction", "-"),
    ("reaction is not a combination of measured reactions", "-"),
    ("compound never measured in any TECRDB reaction", "open"),
    ("no KEGG compound for", "open"),
    ("no AlphaFold DB entry", "-"),
    ("model file missing", "-"),
    ("no pKa data for a participant", "open"),
    ("no K_i in SABIO-RK", "-"),
    ("no k_cat in SABIO-RK", "-"),
    ("no K_m in SABIO-RK", "-"),
    ("no PaxDb abundance", "-"),
    ("the target is outside the source's scope", "+"),
    ("no net chemical change", "+"),
    ("participant without KEGG id", "open"),
    ("a small participant has no KEGG compound", "open"),
    ("carrier chemistry is not phosphoryl transfer", "+"),
    ("no signature rule applies", "+"),
    ("no wild-type edge with the same", "+"),
    ("rung power needs junction conductances", "-"),
    ("a sibling branch lacks", "-"),
    ("no activation constant", "-"),
    ("a modifier's constant is in no source", "-"),
]


def gate_for(v: dict) -> str | None:
    """Gate letter for an empty or absent verdict (dict form)."""
    if v.get("label") not in (Label.EMPTY.value, Label.ABSENT.value):
        return None
    text = (v.get("blocker") or "") + " " + json.dumps(v.get("detail", {}))
    for key, letter in GATE_RULES:
        if key in text:
            return letter
    # a certified-empty answer completed and found nothing: witnessed, unless a rule says otherwise
    return "+" if v.get("label") == Label.EMPTY.value else "?"


def gate_census(obj) -> Counter:
    """Walk any results structure and count gate letters of every empty/absent verdict."""
    out = Counter()

    def walk(x):
        if isinstance(x, dict):
            if x.get("label") in (Label.EMPTY.value, Label.ABSENT.value):
                out[(x["label"], gate_for(x), (x.get("blocker") or "")[:60])] += 1
            for v in x.values():
                walk(v)
        elif isinstance(x, list):
            for v in x:
                walk(v)
    walk(obj)
    return out


# ------------------------------------------------------------------ ground verdicts

CONTACT = {"EquilibriumMeasurement", "KineticAssay", "AbundanceMeasurement", "CrystalStructure"}
DERIVATION = {"Pooling", "HessDerivation", "LegendreTransform", "CarrierSlotDecomposition",
              "StructurePrediction", "ContactGraphComputation", "EnzymeExpansion",
              "WindowJudgement", "RatioComputation", "LadderEvaluation"}
GROUND = {(0, 0, 0): "symbol", (1, 0, 0): "collapsed", (1, 1, 0): "index",
          (1, 0, 1): "icon", (1, 1, 1): "composite"}


class Prov:
    """A tiny PROV graph: records generated by typed activities that used other records."""

    def __init__(self):
        self.generated_by, self.activity_type, self.used = {}, {}, {}

    def activity(self, aid, atype, used=()):
        self.activity_type[aid] = atype
        self.used[aid] = list(used)
        return aid

    def record(self, rid, activity=None):
        if activity is not None:
            self.generated_by[rid] = activity
        return rid

    def ground(self, rid) -> str:
        a0 = self.generated_by.get(rid)
        if a0 is None:
            return "symbol"
        c = d = 0
        seen, todo = set(), [a0]
        while todo:
            a = todo.pop()
            if a in seen:
                continue
            seen.add(a)
            t = self.activity_type.get(a)
            c |= t in CONTACT
            d |= t in DERIVATION
            for u in self.used.get(a, ()):
                if u in self.generated_by:
                    todo.append(self.generated_by[u])
        return GROUND.get((1, c, d), "collapsed")


def kernel_prov() -> tuple[Prov, dict]:
    """The provenance of each fact family the kernel produces (one representative record each)."""
    P = Prov()
    P.record("reactome:stoichiometry", P.activity("curation:reactome", "Curation"))
    P.record("uniprot:ec", P.activity("curation:uniprot", "Curation"))
    P.record("tecrdb:row", P.activity("tecrdb:measure", "EquilibriumMeasurement"))
    P.record("eq:microspecies", P.activity("eq:pka", "Curation"))
    P.record("kernel:dG_measured", P.activity("kernel:pool", "Pooling", ["tecrdb:row"]))
    P.record("kernel:dG_hess", P.activity("kernel:hess", "HessDerivation", ["kernel:dG_measured"]))
    P.record("kernel:dG_slot", P.activity("kernel:slot", "CarrierSlotDecomposition",
                                          ["kernel:dG_hess", "reactome:stoichiometry"]))
    P.record("kernel:dG_prime", P.activity("kernel:legendre", "LegendreTransform",
                                           ["kernel:dG_measured", "eq:microspecies"]))
    P.record("kernel:direction", P.activity("kernel:window", "WindowJudgement", ["kernel:dG_prime"]))
    P.record("af:model", P.activity("af:predict", "StructurePrediction"))
    P.record("kernel:contact_graph", P.activity("kernel:contacts", "ContactGraphComputation",
                                                ["af:model"]))
    P.record("pdb:structure", P.activity("pdb:xray", "CrystalStructure"))
    P.record("kernel:pdb_distance", P.activity("kernel:dist", "ContactGraphComputation",
                                               ["pdb:structure"]))
    P.record("sabio:parameter", P.activity("sabio:assay", "KineticAssay"))
    P.record("paxdb:ppm", P.activity("paxdb:ms", "AbundanceMeasurement"))
    P.record("kernel:retention", P.activity("kernel:ratio", "RatioComputation",
                                            ["sabio:parameter", "paxdb:ppm"]))
    P.record("kernel:enzyme_cycle", P.activity("kernel:expand", "EnzymeExpansion",
                                               ["reactome:stoichiometry"]))
    P.record("kernel:potential_mu")          # never stored: no generation recorded
    families = {r: P.ground(r) for r in P.generated_by} | {"kernel:potential_mu":
                                                          P.ground("kernel:potential_mu")}
    return P, families


# ------------------------------------------------------------------ stages

def digest_file(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def stage(inputs: dict, conventions: dict) -> dict:
    """inputs: name -> path; conventions: name -> JSON-able value.  The stage digest covers both."""
    content = {k: digest_file(Path(p)) for k, p in sorted(inputs.items())}
    conv = hashlib.sha256(json.dumps(conventions, sort_keys=True).encode()).hexdigest()
    total = hashlib.sha256(json.dumps([content, conv], sort_keys=True).encode()).hexdigest()
    return {"inputs": {k: str(p) for k, p in sorted(inputs.items())}, "content": content,
            "conventions_digest": conv, "digest": total}


def is_current(st: dict, conventions: dict) -> bool:
    return stage(st["inputs"], conventions)["digest"] == st["digest"]


# ------------------------------------------------------------------ ladders

def judge_ladder(powers, target: float) -> Verdict:
    """Composite power 1 - prod(1 - p); SUBFLOOR with the shortfall below the target."""
    if not powers:
        return Verdict(Label.EMPTY, detail={"reading": "a rungless ladder"})
    q = 1.0
    for p in powers:
        q *= 1 - p
    comp = 1 - q
    if comp < target:
        return Verdict(Label.SUBFLOOR, blocker="composite power below the declared target",
                       detail={"composite": comp, "target": target, "shortfall": target - comp})
    return answered(comp, target=target)


# ------------------------------------------------------------------ check markers

def check(name: str, passed: bool, control_passed: bool | None) -> dict:
    """status: pass / fail / non-discriminating (the control passed too) / uncontrolled."""
    if control_passed is None:
        status = "pass (uncontrolled)" if passed else "fail"
    elif passed and control_passed:
        status = "non-discriminating"
    else:
        status = "pass" if passed else "fail"
    return {"check": name, "passed": bool(passed), "control_passed": control_passed,
            "status": status}
